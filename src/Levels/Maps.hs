-- đọc map và trả về (bảng tra map, danh sách lỗi). Nếu file map thiếu hoặc sai, dùng bản đồ dựng sẵn
loadMapTableWithErrors :: FilePath -> IO (MapTable, [String])
loadMapTableWithErrors dir = do
  loaded <- mapM loadOne [minBound .. maxBound]

  let table m =
        fromMaybe (mapLayout m)
          (lookup m [(mid, lay) | (mid, lay, _) <- loaded])

      errors =
        [ msg | (_, _, Just msg) <- loaded ]

  pure (table, errors)
  where
    loadOne :: MapId -> IO (MapId, MapLayout, Maybe String)
    loadOne m = do
      r <- loadMapFile (dir </> ("map" ++ show (mapNumber m) ++ ".txt"))

      case r of
        Right lay ->
          pure (m, lay, Nothing)

        Left err -> do
          let msg =
                "Map " ++ show (mapNumber m)
                  ++ ": " ++ describeError err

          hPutStrLn stderr
            ("[maps] " ++ msg
              ++ "\n[maps] using built-in map " ++ show (mapNumber m))

          pure (m, mapLayout m, Just msg)


-- Bản đồ dựng sẵn
mapLayout :: MapId -> MapLayout
mapLayout m =
  either (const borderOnly) id
    (parseMapText "<built-in>" (unlines (builtinRows m)))

borderOnly :: MapLayout
borderOnly = MapLayout
  [ Wall (cellPos c r) SolidSteel steelHp
  | r <- [0 .. arenaRows - 1]
  , c <- [0 .. arenaCols - 1]
  , r == 0 || r == arenaRows - 1 || c == 0 || c == arenaCols - 1 ]
  [] []

